import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { chromium } = require(process.env.CCPS_PLAYWRIGHT_PATH || "playwright");

const browser = await chromium.launch({ headless: true, executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome" });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
const checks = [];
const check = (name, pass, detail = "") => checks.push({ name, pass: Boolean(pass), detail });

await page.goto("http://127.0.0.1:4173/", { waitUntil: "networkidle" });
check("quick links visible",await page.locator("#quickLinks").isVisible());
check("GPT image link",await page.inputValue("#imageToolLink")==="https://chatgpt.com/");
check("ChatArt Pro link",await page.inputValue("#videoToolLink")==="https://app.chatartpro.com/");
check("6 social platform choices",await page.locator("#socialPlatformLink option").count()===6);
await page.selectOption("#socialPlatformLink",{label:"Threads 首頁"});
check("social selection",await page.inputValue("#socialPlatformLink")==="https://www.threads.net/");
await page.evaluate(()=>{window.__openedLink=null;window.open=(url,target,features)=>{window.__openedLink={url,target,features}}});
await page.click('[data-open-link="socialPlatformLink"]');
check("safe selected link open",await page.evaluate(()=>window.__openedLink?.url==="https://www.threads.net/"&&window.__openedLink?.target==="_blank"&&window.__openedLink?.features==="noopener,noreferrer"));
check("article evidence fields absent",await page.locator("#evidenceState,#sourceDate,#evidence").count()===0);
await page.click("#generate");
check("direct article generation",(await page.textContent("#gate")).includes("PASS"));
check("article output CTA",(await page.textContent("#output")).includes("追蹤ccps家慶佳業"));
check("4 platform asset choices",await page.locator("#platformAssetType option").count()===4);
check("video durations",await page.locator("#videoDuration option").allTextContents().then(x=>x.join(",")==="15 秒,30 秒,60 秒"));
check("8+ video styles",await page.locator("#videoStyle option").count()>=8);
await page.selectOption("#platformAssetType",{label:"IG 五張輪播"});await page.click("#generatePlatformAsset");
check("IG five slide output",(await page.textContent("#platformAssetOutput")).match(/第 [1-5] 張｜/g)?.length===5);
await page.selectOption("#platformAssetType",{label:"影片腳本與分鏡"});await page.selectOption("#videoDuration",{label:"60 秒"});await page.click("#generatePlatformAsset");
const videoOutput=await page.textContent("#platformAssetOutput");
check("60 second storyboard",videoOutput.includes("【60 秒影片腳本與逐鏡分鏡】")&&videoOutput.includes("分鏡圖提示詞：")&&videoOutput.includes("追蹤ccps家慶佳業"));
check("header logo visible",await page.locator(".brand-logo").isVisible());
await page.click('[data-tab="brand"]');
const brandSelectIds=["brandPosition","brandArea","brandAudience","brandTone","brandPrinciples","brandForbidden","voiceTone","voiceColloquial","voicePerson","voiceWords","voiceForbidden","voiceNever","voicePrinciples","voiceExamples"];
check("brand selects have 8+ choices",await page.evaluate(ids=>ids.every(id=>document.getElementById(id)?.options.length>=8),brandSelectIds));
check("brand ending locked",await page.locator("#brandEnding").isDisabled()||await page.locator("#brandEnding").getAttribute("readonly")!==null);
await page.selectOption("#brandPosition",{index:7});
await page.selectOption("#voiceTone",{index:7});
const savedBrandPosition=await page.inputValue("#brandPosition"),savedVoiceTone=await page.inputValue("#voiceTone");
await page.click("#saveBrand");await page.click("#saveVoice");await page.reload({waitUntil:"networkidle"});await page.click('[data-tab="brand"]');
check("brand choices persist",await page.inputValue("#brandPosition")===savedBrandPosition&&await page.inputValue("#voiceTone")===savedVoiceTone);
await page.click('[data-tab="materials"]');
await page.waitForFunction(() => document.querySelector("#officialSummary")?.textContent?.includes("置產寶典 34"));
check("combined count", (await page.textContent("#officialSummary")).includes("共 185 筆"));
check("guide count", (await page.textContent("#officialSummary")).includes("置產寶典 34"));
check("mobile no horizontal overflow", await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth));
await page.selectOption("#officialSource", { label: "馬來西亞置產寶典" });
check("source filter", (await page.textContent("#officialSummary")).includes("30／34 筆"));
check("memory boundary visible", (await page.locator("#officialList article").first().textContent()).includes("MEMORY_DERIVED"));
await page.fill("#officialSearch", "MM2H");
check("search result", await page.locator("#officialList article").count() >= 1);
check("source link", (await page.locator("#officialList article a").first().getAttribute("href")).startsWith("https://ccps-malaysia-property-guide.netlify.app/"));
await page.fill("#officialSearch", "");
check("sealed source option absent", !(await page.locator("#officialSource").textContent()).includes("公司股權"));
check("internal marker absent", !(await page.locator("body").textContent()).includes("INTERNAL_ONLY"));

checks.forEach(x => console.log(`${x.pass ? "PASS" : "FAIL"} ${x.name}${x.detail ? ` — ${x.detail}` : ""}`));
const failed = checks.filter(x => !x.pass);
console.log(`\n${checks.length - failed.length}/${checks.length} PASS`);
await browser.close();
process.exit(failed.length ? 1 : 0);
